package 阶段6.C网格路径DP;

/**
 * 62. 不同路径
 * 已解答
 * 中等
 * 相关标签
 * premium lock icon
 * 相关企业
 * 题目描述：
 * 一个机器人位于一个 m x n 网格的左上角 （起始点在下图中标记为 “Start” ）。
 * 机器人每次只能向下或者向右移动一步。机器人试图达到网格的右下角（在下图中标记为 “Finish” ）。
 * 问总共有多少条不同的路径？
 * <p>
 * 示例 1：
 * 输入：m = 3, n = 7
 * 输出：28
 * <p>
 * 示例 2：
 * 输入：m = 3, n = 2
 * 输出：3
 * 解释：
 * 从左上角开始，总共有 3 条路径可以到达右下角。
 * 1. 向右 -> 向下 -> 向下
 * 2. 向下 -> 向下 -> 向右
 * 3. 向下 -> 向右 -> 向下
 * <p>
 * 动态规划思路：
 * 状态定义：dp[i][j] 表示走到网格第 i 行、第 j 列这个位置，一共有多少条路径
 * 转移方程：dp[i][j] = dp[i-1][j] + dp[i][j-1]
 * 含义：机器人只能从【上方(i-1,j)往下走】或者【左边(i,j-1)往右走】到达当前位置
 * 边界条件：
 * 第一列（j=0）：只能一直向下走，所有位置路径数都是 1
 * 第一行（i=0）：只能一直向右走，所有位置路径数都是 1
 * <p>
 * 注意：使用long类型存储，防止数字过大int溢出
 */
public class LC62 {
    public static void main(String[] args) {
        // 测试用例：3行7列，预期输出28
        System.out.println(uniquePaths(3, 7));
    }

    /**
     * @param m 网格行数
     * @param n 网格列数
     * @return 从左上角走到右下角的路径总数
     */
    public static int uniquePaths(int m, int n) {
        // arr[i][j]：走到i行j列的路径数量，long防止溢出
        long[][] arr = new long[m][n];

        // 初始化第一列：所有行，j=0
        // 第一列只能从上往下走，只有1种走法
        for (int i = 0; i < m; i++) {
            arr[i][0] = 1;
        }

        // 初始化第一行：所有列，i=0
        // 第一行只能从左往右走，只有1种走法
        for (int i = 0; i < n; i++) {
            arr[0][i] = 1;
        }

        // 双重循环递推，i从第1行开始，j从第1列开始
        // 第0行、第0列已经初始化完成，不需要再计算
        for (int i = 1; i < m; i++) {
            for (int j = 1; j < n; j++) {
                // 当前位置路径数 = 上方位置路径数 + 左侧位置路径数
                arr[i][j] = arr[i - 1][j] + arr[i][j - 1];
            }
        }

        // 终点是右下角：下标 m-1, n-1，long转回int返回
        return (int) (arr[m - 1][n - 1]);
    }
}
